#!/bin/sh
# Bundle the demo into one self-contained HTML file.
#
# The output works from `file://` (double-click), because nothing is fetched:
# the ES module becomes a blob URL and the wasm becomes base64 in a data string.
#
#   bash scripts/web-bundle.sh            -> target/soma-kp-standalone.html
#   bash scripts/web-bundle.sh out.html   -> a chosen path
set -eu

cd "$(dirname "$0")/.."
out=${1:-target/soma-kp-standalone.html}

if [ ! -f web/soma-kp.wasm ]; then
    echo "web/soma-kp.wasm is missing; run 'bash scripts/web.sh' first" >&2
    exit 1
fi

mkdir -p "$(dirname "$out")"
python3 - "$out" <<'PY'
import base64
import json
import pathlib
import sys

root = pathlib.Path('.')
html = (root / 'web/demo.html').read_text(encoding='utf-8')
module = (root / 'web/soma-kp.js').read_text(encoding='utf-8')
wasm = (root / 'web/soma-kp.wasm').read_bytes()

prelude = (
    '<script>\n'
    '// Generated by scripts/web-bundle.sh — do not edit.\n'
    'window.__somaKpUrl = URL.createObjectURL('
    'new Blob([' + json.dumps(module) + "], { type: 'text/javascript' }));\n"
    'window.__somaKpWasm = "' + base64.b64encode(wasm).decode('ascii') + '";\n'
    '</script>\n'
)

marker = '<script type="module">'
if marker not in html:
    sys.exit('demo.html has no module script to bundle')
bundled = html.replace(marker, prelude + marker, 1)
bundled = bundled.replace(
    '<title>soma-kp · 浏览器断行演示</title>',
    '<title>soma-kp · 浏览器断行演示（单文件）</title>',
    1,
)
pathlib.Path(sys.argv[1]).write_text(bundled, encoding='utf-8')
print(f'wrote {sys.argv[1]} ({len(bundled.encode("utf-8"))} bytes, '
      f'{len(wasm)} B wasm inlined)')
PY
