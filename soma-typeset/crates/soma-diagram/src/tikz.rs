//! TikZ source export from the computed geometry.
//!
//! The export is exact for the default label size (1 em): it emits the same
//! paths and baseline anchors the renderers draw, using only the core TikZ
//! drawing language (no `shapes`/`arrows` libraries). It is an interop and
//! inspection tool, not the rendering path.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;

use soma_core::Width;
use soma_tikz::{Path, Point, Segment};

use crate::layout::{DiagramLayout, TextRun};

pub fn to_tikz(layout: &DiagramLayout) -> String {
    let mut out = String::new();
    out.push_str("% Generated by soma-diagram (ADR-0102).\n");
    out.push_str("\\begin{tikzpicture}\n");
    for path in &layout.tikz.paths {
        write_path(&mut out, path);
    }
    for rule in &layout.tikz.rules {
        out.push_str("\\draw[line width=");
        out.push_str(&em(rule.thickness));
        out.push_str("em] (");
        out.push_str(&em(rule.x));
        out.push_str("em");
        out.push(',');
        out.push_str(&em(rule.y));
        out.push_str("em");
        out.push_str(") -- (");
        out.push_str(&em(Width(rule.x.0 + rule.width.0)));
        out.push_str("em");
        out.push(',');
        out.push_str(&em(rule.y));
        out.push_str("em");
        out.push_str(");\n");
    }
    for text in &layout.texts {
        write_text(&mut out, text);
    }
    out.push_str("\\end{tikzpicture}\n");
    out
}

fn write_path(out: &mut String, path: &Path) {
    let mut options: Vec<String> = Vec::new();
    if let Some(stroke) = &path.stroke {
        options.push(format!("draw={}", color(stroke.color)));
        options.push(format!("line width={}em", em(stroke.width)));
        if !stroke.dash.is_empty() {
            let mut dash = String::from("dash pattern=");
            for (index, value) in stroke.dash.iter().enumerate() {
                if index > 0 {
                    dash.push(' ');
                }
                dash.push_str(if index % 2 == 0 { "on " } else { "off " });
                dash.push_str(&em(*value));
                dash.push_str("em");
            }
            options.push(dash);
        }
    }
    if let Some(fill) = path.fill {
        options.push(format!("fill={}", color(fill)));
    }
    if options.is_empty() {
        return;
    }
    out.push_str("\\path[");
    out.push_str(&options.join(","));
    out.push_str("] ");
    point(out, path.start);
    for segment in &path.segments {
        match segment {
            Segment::Line(to) => {
                out.push_str(" -- ");
                point(out, *to);
            }
            Segment::Cubic { c1, c2, to } => {
                out.push_str(" .. controls ");
                point(out, *c1);
                out.push_str(" and ");
                point(out, *c2);
                out.push_str(" .. ");
                point(out, *to);
            }
            Segment::Close => out.push_str(" -- cycle"),
        }
    }
    out.push_str(";\n");
}

fn write_text(out: &mut String, text: &TextRun) {
    out.push_str("\\node[anchor=base,inner sep=0pt,outer sep=0pt,text=");
    out.push_str(&color(text.color));
    if text.size.0 != Width::EM.0 && text.size.0 > 0 {
        let leading = text.size.scale(6, 5);
        out.push_str(",font=\\fontsize{");
        out.push_str(&em(text.size));
        out.push_str("}{");
        out.push_str(&em(leading));
        out.push_str("}\\selectfont");
    }
    out.push_str("] at (");
    out.push_str(&em(Width(text.x.0 + text.width.0 / 2)));
    out.push_str("em");
    out.push(',');
    out.push_str(&em(text.baseline));
    out.push_str("em");
    out.push_str(") {");
    out.push_str(&escape(&text.text));
    out.push_str("};\n");
}

fn point(out: &mut String, point: Point) {
    out.push('(');
    out.push_str(&em(point.x));
    out.push_str("em");
    out.push(',');
    out.push_str(&em(point.y));
    out.push_str("em");
    out.push(')');
}

fn color(value: u32) -> String {
    if value == 0 {
        String::from("black")
    } else if value == 0xffffff {
        String::from("white")
    } else {
        format!(
            "{{rgb,255:red,{};green,{};blue,{}}}",
            (value >> 16) & 0xff,
            (value >> 8) & 0xff,
            value & 0xff
        )
    }
}

/// Integer fixed-point to decimal em, four fractional digits, no float.
fn em(value: Width) -> String {
    let mut value = value.0;
    let negative = value < 0;
    if negative {
        value = -value;
    }
    let whole = value / 4096;
    let fraction = i64::from(value % 4096) * 10_000 / 4096;
    let mut out = String::new();
    if negative {
        out.push('-');
    }
    out.push_str(&format!("{whole}"));
    if fraction > 0 {
        let mut digits = format!("{fraction:04}");
        while digits.ends_with('0') {
            digits.pop();
        }
        out.push('.');
        out.push_str(&digits);
    }
    out
}

fn escape(text: &str) -> String {
    let mut out = String::new();
    for ch in text.chars() {
        match ch {
            '\\' => out.push_str("\\textbackslash{}"),
            '{' => out.push_str("\\{"),
            '}' => out.push_str("\\}"),
            '%' => out.push_str("\\%"),
            '&' => out.push_str("\\&"),
            '#' => out.push_str("\\#"),
            '_' => out.push_str("\\_"),
            '$' => out.push_str("\\$"),
            '^' => out.push_str("\\textasciicircum{}"),
            '~' => out.push_str("\\textasciitilde{}"),
            other => out.push(other),
        }
    }
    out
}
