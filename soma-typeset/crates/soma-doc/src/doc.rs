//! The document root.

use alloc::string::String;
use alloc::vec::Vec;

use crate::block::{Block, GeneratedBlock, List, ListItem, Row, Section, Table};
use crate::canonical::{self, CanonicalMode};
use crate::hash::{self, DocHash};
use crate::ids::SourceMap;
use crate::inline::Inline;
use crate::meta::DocumentMeta;
use crate::node::NodeMeta;
use crate::text;
use crate::validate::{self, DocError};

/// Canonical schema id. Changing the emitted shape requires a new id.
pub const SCHEMA: &str = "soma.doc/2";

/// Structural version of the DocIR model. Additive node kinds keep the version;
/// changing the meaning of an existing field does not.
pub const DOC_IR_VERSION: u16 = 2;

/// A footnote definition. Referenced by [`crate::FootnoteRef::target`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FootnoteDef {
    pub meta: NodeMeta,
    /// Stable label inside the document (`1`, `note-a`). Visible numbering is
    /// generated by the template.
    pub label: String,
    pub blocks: Vec<Block>,
}

impl FootnoteDef {
    pub fn new(meta: NodeMeta, label: impl Into<String>, blocks: Vec<Block>) -> Self {
        Self {
            meta,
            label: label.into(),
            blocks,
        }
    }
}

/// A complete semantic document.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Document {
    pub meta: DocumentMeta,
    pub blocks: Vec<Block>,
    pub footnotes: Vec<FootnoteDef>,
    pub source_map: SourceMap,
}

impl Document {
    pub const SCHEMA: &'static str = SCHEMA;
    pub const DOC_IR_VERSION: u16 = DOC_IR_VERSION;

    pub fn new(meta: DocumentMeta) -> Self {
        Self {
            meta,
            ..Self::default()
        }
    }

    pub fn with_meta(mut self, meta: DocumentMeta) -> Self {
        self.meta = meta;
        self
    }

    pub fn push_block(&mut self, block: Block) {
        self.blocks.push(block);
    }

    pub fn push_footnote(&mut self, definition: FootnoteDef) {
        self.footnotes.push(definition);
    }

    pub fn find_footnote(&self, label: &str) -> Option<&FootnoteDef> {
        self.footnotes
            .iter()
            .find(|definition| definition.label == label)
    }

    /// Assign node ids in a deterministic pre-order walk, starting at 1.
    ///
    /// Traversal order is part of the contract because ids appear in canonical
    /// output:
    ///
    /// 1. `meta.title` inlines;
    /// 2. blocks in document order, each block before its children;
    /// 3. within a table: columns, then caption, then rows (row, then cells,
    ///    then cell blocks);
    /// 4. within a figure: image, then caption;
    /// 5. footnotes in document order, each definition before its blocks.
    pub fn renumber(&mut self) {
        let mut next = 1u32;
        self.for_each_meta_mut(&mut |meta| {
            meta.id = crate::ids::NodeId::new(next);
            next += 1;
        });
    }

    /// Number of nodes (blocks, inlines, table parts, footnote definitions).
    /// Equals the highest assigned id after [`Self::renumber`].
    pub fn node_count(&self) -> u32 {
        let mut count = 0u32;
        self.for_each_meta(&mut |_| count += 1);
        count
    }

    /// Assigned ids in traversal order. Used by diagnostics, incremental layout,
    /// and tests that pin renumbering.
    pub fn node_ids(&self) -> Vec<crate::ids::NodeId> {
        let mut ids = Vec::new();
        self.for_each_meta(&mut |meta| ids.push(meta.id));
        ids
    }

    /// Validate structure, ids, spans, references, and bounds.
    pub fn validate(&self) -> Result<(), DocError> {
        validate::validate(self)
    }

    /// Canonical JSON of the full document, including ids, spans, and sources.
    pub fn write_canonical(&self, out: &mut impl core::fmt::Write) -> core::fmt::Result {
        canonical::write_document(out, self, CanonicalMode::Full)
    }

    /// Canonical JSON as a `String`.
    pub fn canonical_json(&self) -> String {
        canonical::canonical_json(self, CanonicalMode::Full)
    }

    /// Canonical JSON with provenance normalised away. Two documents with equal
    /// content produce equal bytes even if parsed from different files.
    pub fn canonical_content_json(&self) -> String {
        canonical::canonical_json(self, CanonicalMode::Content)
    }

    /// Full hash: ids, spans, source map, template reference.
    pub fn doc_hash(&self) -> DocHash {
        hash::document_hash(self)
    }

    /// Content hash: ids, spans, source map, and template reference normalised
    /// away. Use this as the "content changed?" cache key.
    pub fn content_hash(&self) -> DocHash {
        hash::content_hash(self)
    }

    /// Human-readable text projection: used for titles, TOC entries, alt-text
    /// fallbacks, and diagnostics. Not a renderer.
    pub fn plain_text(&self) -> String {
        let mut out = String::new();
        text::write_blocks(&mut out, &self.blocks);
        out
    }

    /// Plain text of the document title, if any.
    pub fn title_text(&self) -> Option<String> {
        self.meta.title.as_ref().map(|inlines| {
            let mut out = String::new();
            text::write_inlines(&mut out, inlines);
            let trimmed = out.trim_end();
            String::from(trimmed)
        })
    }

    /// Visit every node header in the same order as [`Self::renumber`].
    pub(crate) fn for_each_meta(&self, f: &mut impl FnMut(&NodeMeta)) {
        if let Some(title) = &self.meta.title {
            visit_inlines(title, f);
        }
        visit_blocks(&self.blocks, f);
        for definition in &self.footnotes {
            f(&definition.meta);
            visit_blocks(&definition.blocks, f);
        }
    }

    /// Mutable counterpart of [`Self::for_each_meta`]. The two walks must visit
    /// the same nodes in the same order; a test pins that.
    pub(crate) fn for_each_meta_mut(&mut self, f: &mut impl FnMut(&mut NodeMeta)) {
        if let Some(title) = &mut self.meta.title {
            visit_inlines_mut(title, f);
        }
        visit_blocks_mut(&mut self.blocks, f);
        for definition in &mut self.footnotes {
            f(&mut definition.meta);
            visit_blocks_mut(&mut definition.blocks, f);
        }
    }
}

fn visit_blocks(blocks: &[Block], f: &mut impl FnMut(&NodeMeta)) {
    for block in blocks {
        visit_block(block, f);
    }
}

fn visit_block(block: &Block, f: &mut impl FnMut(&NodeMeta)) {
    f(block.meta());
    match block {
        Block::Paragraph(node) => visit_inlines(&node.inlines, f),
        Block::Heading(node) => visit_inlines(&node.inlines, f),
        Block::List(node) => visit_list(node, f),
        Block::BlockQuote(node) => visit_blocks(&node.blocks, f),
        Block::Figure(node) => {
            f(&node.image.meta);
            visit_inlines(&node.caption, f);
        }
        Block::Table(node) => visit_table(node, f),
        Block::Section(node) => visit_section(node, f),
        Block::Generated(node) => visit_generated(node, f),
        Block::CodeBlock(_)
        | Block::MathBlock(_)
        | Block::ThematicBreak(_)
        | Block::PageBreak(_)
        | Block::Raw(_) => {}
    }
}

fn visit_list(list: &List, f: &mut impl FnMut(&NodeMeta)) {
    for item in &list.items {
        f(&item.meta);
        visit_blocks(&item.blocks, f);
    }
}

fn visit_table(table: &Table, f: &mut impl FnMut(&NodeMeta)) {
    for column in &table.columns {
        f(&column.meta);
    }
    visit_inlines(&table.caption, f);
    for row in &table.rows {
        visit_row(row, f);
    }
}

fn visit_row(row: &Row, f: &mut impl FnMut(&NodeMeta)) {
    f(&row.meta);
    for cell in &row.cells {
        f(&cell.meta);
        visit_blocks(&cell.blocks, f);
    }
}

fn visit_section(section: &Section, f: &mut impl FnMut(&NodeMeta)) {
    if let Some(title) = &section.title {
        visit_inlines(title, f);
    }
}

fn visit_generated(generated: &GeneratedBlock, f: &mut impl FnMut(&NodeMeta)) {
    visit_blocks(&generated.blocks, f);
}

fn visit_inlines(inlines: &[Inline], f: &mut impl FnMut(&NodeMeta)) {
    for inline in inlines {
        f(inline.meta());
        visit_inlines(inline.children(), f);
    }
}

fn visit_blocks_mut(blocks: &mut [Block], f: &mut impl FnMut(&mut NodeMeta)) {
    for block in blocks {
        visit_block_mut(block, f);
    }
}

fn visit_block_mut(block: &mut Block, f: &mut impl FnMut(&mut NodeMeta)) {
    f(block.meta_mut());
    match block {
        Block::Paragraph(node) => visit_inlines_mut(&mut node.inlines, f),
        Block::Heading(node) => visit_inlines_mut(&mut node.inlines, f),
        Block::List(node) => {
            for item in &mut node.items {
                visit_item_mut(item, f);
            }
        }
        Block::BlockQuote(node) => visit_blocks_mut(&mut node.blocks, f),
        Block::Figure(node) => {
            f(&mut node.image.meta);
            visit_inlines_mut(&mut node.caption, f);
        }
        Block::Table(node) => {
            for column in &mut node.columns {
                f(&mut column.meta);
            }
            visit_inlines_mut(&mut node.caption, f);
            for row in &mut node.rows {
                f(&mut row.meta);
                for cell in &mut row.cells {
                    f(&mut cell.meta);
                    visit_blocks_mut(&mut cell.blocks, f);
                }
            }
        }
        Block::Section(node) => {
            if let Some(title) = &mut node.title {
                visit_inlines_mut(title, f);
            }
        }
        Block::Generated(node) => visit_blocks_mut(&mut node.blocks, f),
        Block::CodeBlock(_)
        | Block::MathBlock(_)
        | Block::ThematicBreak(_)
        | Block::PageBreak(_)
        | Block::Raw(_) => {}
    }
}

fn visit_item_mut(item: &mut ListItem, f: &mut impl FnMut(&mut NodeMeta)) {
    f(&mut item.meta);
    visit_blocks_mut(&mut item.blocks, f);
}

fn visit_inlines_mut(inlines: &mut [Inline], f: &mut impl FnMut(&mut NodeMeta)) {
    for inline in inlines {
        f(inline.meta_mut());
        if let Some(children) = inline.children_mut() {
            visit_inlines_mut(children, f);
        }
    }
}
