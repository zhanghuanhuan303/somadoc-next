#!/usr/bin/env python3
"""Generate `STANDARD_ENCODING_SID` for the PDF backend's seac handling.

A Type 2 `endchar` with four operands (the `seac` form) names its base and
accent glyphs by StandardEncoding *code*. Inside a name-keyed CFF a glyph is
identified by its SID, so a code has to become a SID:

    code --StandardEncoding--> glyph name --CFF standard strings--> SID

Both inputs are normative tables from the specifications:

* StandardEncoding: `Resource/Init/gs_std_e.ps` from Ghostscript (the same
  array is printed in the PostScript Language Reference, Appendix E).
* The CFF standard strings, Appendix A: taken here from luaotfload's
  `fontloader-font-cff.lua`, which reproduces the list verbatim.

    python3 tools/make-standard-encoding.py \
        /usr/share/ghostscript/Resource/Init/gs_std_e.ps \
        /usr/share/texmf-dist/tex/luatex/luaotfload/fontloader-font-cff.lua \
        crates/soma-render-pdf/src/standard_encoding.rs
"""

import re
import sys

# Codes with no glyph in StandardEncoding (and every unused slot) get this.
MISSING = 0xFFFF


def standard_encoding(path):
    lines = open(path).read().split("\n")
    start = next(i for i, line in enumerate(lines) if line.strip() == "/StandardEncoding")
    names = []
    for line in lines[start + 1:]:
        if line.strip() == "256":
            break
        if line.strip().startswith("%"):
            continue
        names += re.findall(r"/([A-Za-z0-9_.]+)", line)
    if len(names) != 256:
        raise SystemExit(f"{path}: expected 256 codes, found {len(names)}")
    return names


def standard_strings(path):
    text = open(path).read()
    start = text.find("local defaultstrings = { [0] =")
    end = text.find("}", start)
    body = text[text.find("[0] =", start) + len("[0] ="):end]
    body = body.replace("-- taken from ff", "")
    names = re.findall(r'"([^"]*)"', body)
    if len(names) != 391:
        raise SystemExit(f"{path}: expected 391 strings, found {len(names)}")
    return names


def main():
    encoding = standard_encoding(sys.argv[1])
    strings = standard_strings(sys.argv[2])
    index = {name: sid for sid, name in enumerate(strings)}
    sids = [index.get(name, MISSING) for name in encoding]

    out = [
        "//! StandardEncoding code to CFF standard-string SID.",
        "//!",
        "//! Generated by `tools/make-standard-encoding.py` from Ghostscript's",
        "//! `gs_std_e.ps` (StandardEncoding) and the CFF standard strings in",
        "//! Appendix A of the specification. Do not edit by hand.",
        "",
        "/// `0xFFFF` means the code has no glyph, so a `seac` that names it is",
        "/// unresolvable.",
        "pub(crate) const STANDARD_ENCODING_SID: [u16; 256] = [",
    ]
    for row in range(0, 256, 8):
        values = ", ".join(
            "0xffff" if sid == MISSING else f"0x{sid:04x}" for sid in sids[row:row + 8]
        )
        out.append(f"    {values}, // {row:#04x}")
    out.append("];")
    out.append("")
    open(sys.argv[3], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
